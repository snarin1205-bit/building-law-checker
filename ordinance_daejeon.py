def _norm(s):
    return "".join(str(s).split())


def zone_limits(zone_names):
    """VWorld 용도지역명 → 대전광역시 도시계획 조례 기준 건폐율·용적률 상한.

    매칭 실패는 '미확인'(unmatched)으로 남기고 추정하지 않는다."""
    matches, unmatched = [], []
    for z in zone_names or []:
        k = _norm(z)
        if not k:
            continue
        if k in DJ_ZONE_LIMITS:
            cov, far, note = DJ_ZONE_LIMITS[k]
            matches.append({"zone": z, "coverage_max_pct": cov, "far_max_pct": far, "note": note})
        else:
            unmatched.append(z)
    status = "UNKNOWN" if not matches else ("PARTIAL" if unmatched else "OK")
    return {"status": status, "matches": matches, "unmatched": unmatched,
            "overlap": len(matches) + len(unmatched) > 1,
            "caveats": list(DJ_ZONE_CAVEATS), "law": DJ_META["urban"]}


